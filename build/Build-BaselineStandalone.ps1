# Foton standalone baseline build
#
# Ship Baseline capture as one file. Concatenates Private/Core, baseline
# providers, New-FotonBaseline, and New-FotonBaselineReport.
# Does not include Collect, Analyze heuristics, Parse, or compare-HTML (workstation).

[CmdletBinding()]
param(
    [string]$RepoRoot,
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'
if (-not $RepoRoot) { $RepoRoot = Join-Path $PSScriptRoot '..' }
$RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).Path
$srcRoot = Join-Path $RepoRoot 'src'
$psd1 = Import-PowerShellDataFile -LiteralPath (Join-Path $RepoRoot 'Foton.psd1')
$version = [string]$psd1.ModuleVersion
$baseSchema = [string]$psd1.PrivateData.Foton.BaselineSchemaVersion
$aliasPath = $null
if (-not $OutputPath) {
    $leaf = "Foton-Baseline_v${version}_schema${baseSchema}.ps1"
    $OutputPath = Join-Path $RepoRoot "dist\$leaf"
    $aliasPath = Join-Path $RepoRoot 'dist\Foton-Baseline.ps1'
}

$hardeningCsv = Get-Content -LiteralPath (Join-Path $srcRoot 'Private\Patterns\HardeningRegistryChecks.csv') -Raw

# Core first so Register-FotonBaselineProvider exists before provider files run.
$files = @(
    Get-ChildItem -LiteralPath (Join-Path $srcRoot 'Private\Core') -Filter '*.ps1' -File | Sort-Object FullName
    Get-ChildItem -LiteralPath (Join-Path $srcRoot 'Private\Baseline\Providers') -Filter '*.ps1' -File | Sort-Object FullName
    Get-Item -LiteralPath (Join-Path $srcRoot 'Public\Baseline\New-FotonBaseline.ps1')
    Get-Item -LiteralPath (Join-Path $srcRoot 'Public\Report\New-FotonBaselineReport.ps1')
)

$chunks = New-Object System.Text.StringBuilder
foreach ($file in $files) {
    $null = $chunks.AppendLine('')
    $rel = $file.FullName.Substring($RepoRoot.Length).TrimStart('\')
    $null = $chunks.AppendLine("# --- $rel ---")
    $text = Get-Content -LiteralPath $file.FullName -Raw -Encoding UTF8
    if ($text.Length -gt 0 -and [int][char]$text[0] -eq 0xFEFF) {
        $text = $text.Substring(1)
    }
    $null = $chunks.AppendLine($text)
}

$header = @"
<#
.SYNOPSIS
    Foton-Baseline - Windows known-state snapshot (standalone).

.DESCRIPTION
    Flattened baseline capture + HTML snapshot. No Import-Module.
    Writes FotonBaseline_<host>_<stamp>Z with baseline.json, Foton_Baseline.html,
    hashes, and an optional ZIP. Not a live triage collect.

    A baseline taken after an incident is a picture of that state.

.NOTES
    Generated by build/Build-BaselineStandalone.ps1 from Foton $version, baseline schema $baseSchema. Do not hand-edit.
#>
[CmdletBinding()]
param(
    [string]`$OutputPath = "`$env:USERPROFILE\Desktop",
    [switch]`$NoZip,
    [switch]`$NoHtml,
    [switch]`$RequireAdministrator
)

`$ErrorActionPreference = 'Continue'
`$ProgressPreference = 'SilentlyContinue'
`$script:FotonModuleRoot = `$PSScriptRoot
`$script:FotonSrcRoot = `$null
`$script:FotonSession = @{ Version = '$version' }
`$script:FotonEmbeddedPatterns = @{
    UserWritablePatterns      = @()
    SuspiciousCommandPatterns = @()
    RemoteAccessToolNames     = @()
    HardeningCsv              = @'
$hardeningCsv
'@
}
`$script:FotonEmbeddedBaselineSchema = '$baseSchema'
`$script:FotonBaselineProviders = New-Object System.Collections.ArrayList
`$script:FotonColorMode = `$null
`$script:FotonBlockOk = `$null

"@

$footer = @"

# Generated entry: package-mode capture.
New-FotonBaseline @PSBoundParameters
"@

$destDir = Split-Path $OutputPath -Parent
if (-not (Test-Path -LiteralPath $destDir)) {
    New-Item -Path $destDir -ItemType Directory -Force | Out-Null
}

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($OutputPath, ($header + $chunks.ToString() + $footer), $utf8)

$parseErrors = $null
$null = [System.Management.Automation.Language.Parser]::ParseFile($OutputPath, [ref]$null, [ref]$parseErrors)
if ($parseErrors -and $parseErrors.Count -gt 0) {
    $parseErrors | ForEach-Object { Write-Host "LINE $($_.Extent.StartLineNumber): $($_.Message)" -ForegroundColor Red }
    throw "Generated $OutputPath has parse errors."
}

if ($aliasPath) {
    Copy-Item -LiteralPath $OutputPath -Destination $aliasPath -Force
}

Write-Host "Wrote $OutputPath ($([math]::Round((Get-Item $OutputPath).Length / 1KB, 1)) KB, $($files.Count) source files, v$version, baseline schema $baseSchema)" -ForegroundColor Green
if ($aliasPath) {
    Write-Host "Also wrote $aliasPath (same bytes; stable name for docs and RMM)." -ForegroundColor Green
    Write-Host 'Copy the versioned file to the endpoint so the schema is visible in the leaf name. Do not copy the module tree. Do not mix with Foton-Collect.ps1.' -ForegroundColor DarkGray
} else {
    Write-Host 'Copy this file to the endpoint. Do not copy the module tree. Do not mix with Foton-Collect.ps1.' -ForegroundColor DarkGray
}
