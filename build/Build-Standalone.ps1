# Foton standalone collector build
#
# Develop as a module; ship Collect as one file. Concatenates Private/Core,
# Public/Collect, Analyze, Report, and Invoke-FotonTriage. Pattern lists are
# embedded so the endpoint does not need a module tree.
#
# Does not include Get-FotonPackage (workstation) or Get-FotonVersion (needs .psd1).

[CmdletBinding()]
param(
    [string]$RepoRoot,
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'
if (-not $RepoRoot) { $RepoRoot = Join-Path $PSScriptRoot '..' }
$RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).Path
$srcRoot = Join-Path $RepoRoot 'src'
$psd1 = Import-PowerShellDataFile -LiteralPath (Join-Path $RepoRoot 'Foton.psd1')
$version = [string]$psd1.ModuleVersion
$collectSchema = [string]$psd1.PrivateData.Foton.CollectSchemaVersion
$aliasPath = $null
if (-not $OutputPath) {
    $leaf = "Foton-Collect_v${version}_schema${collectSchema}.ps1"
    $OutputPath = Join-Path $RepoRoot "dist\$leaf"
    $aliasPath = Join-Path $RepoRoot 'dist\Foton-Collect.ps1'
}

function Get-FotonPatternLineArray {
    param([string]$Path)
    $out = @()
    foreach ($line in (Get-Content -LiteralPath $Path -ErrorAction Stop)) {
        if ($null -eq $line) { continue }
        if ($line -match '^\s*$') { continue }
        if ($line -match '^\s*#') { continue }
        $out += $line
    }
    return $out
}

function ConvertTo-FotonQuotedArrayLiteral {
    param([string[]]$Lines)
    $out = New-Object System.Collections.Generic.List[string]
    $null = $out.Add('@(')
    foreach ($line in $Lines) {
        $q = [string]$line
        $q = $q.Replace("'", "''")
        $null = $out.Add("        '$q'")
    }
    $null = $out.Add('    )')
    return ($out -join [Environment]::NewLine)
}

$patternDir = Join-Path $srcRoot 'Private\Patterns'
$writable = Get-FotonPatternLineArray (Join-Path $patternDir 'UserWritablePatterns.txt')
$suspicious = Get-FotonPatternLineArray (Join-Path $patternDir 'SuspiciousCommandPatterns.txt')
$rats = Get-FotonPatternLineArray (Join-Path $patternDir 'RemoteAccessToolNames.txt')
$hardeningCsv = Get-Content -LiteralPath (Join-Path $patternDir 'HardeningRegistryChecks.csv') -Raw

$skipNames = @('Get-FotonPackage.ps1', 'Get-FotonVersion.ps1')
$files = @(
    Get-ChildItem -LiteralPath (Join-Path $srcRoot 'Private\Core') -Filter '*.ps1' -File
    Get-ChildItem -LiteralPath (Join-Path $srcRoot 'Public\Collect') -Filter '*.ps1' -File
    Get-Item -LiteralPath (Join-Path $srcRoot 'Public\Analyze\Invoke-FotonAnalysis.ps1')
    Get-Item -LiteralPath (Join-Path $srcRoot 'Public\Report\New-FotonReport.ps1')
    Get-Item -LiteralPath (Join-Path $srcRoot 'Public\Invoke-FotonTriage.ps1')
) | Where-Object { $skipNames -notcontains $_.Name } | Sort-Object { $_.Directory.Name + '\' + $_.Name }, FullName

$chunks = New-Object System.Text.StringBuilder
foreach ($file in $files) {
    $null = $chunks.AppendLine('')
    $rel = $file.FullName.Substring($RepoRoot.Length).TrimStart('\')
    $null = $chunks.AppendLine("# --- $rel ---")
    $text = Get-Content -LiteralPath $file.FullName -Raw -Encoding UTF8
    if ($text.Length -gt 0 -and [int][char]$text[0] -eq 0xFEFF) {
        $text = $text.Substring(1)
    }
    $null = $chunks.AppendLine($text)
}

$header = @"
<#
.SYNOPSIS
    Foton-Collect - Windows DFIR live triage (standalone).

.DESCRIPTION
    Flattened Collect + Analyze + Report. No Import-Module. Same parameters as
    WinFoton.ps1. Case folders are named Foton_<host>_<stamp>Z.

    LIVE COLLECTION: running this modifies the target. Findings are observations.

.NOTES
    Generated by build/Build-Standalone.ps1 from Foton $version, collect schema $collectSchema. Do not hand-edit.
#>
[CmdletBinding()]
param(
    [string]`$OutputPath = "`$env:USERPROFILE\Desktop",
    [string]`$CaseNumber = "",
    [string]`$Examiner = "`$env:USERNAME",
    [int]`$EventLogDays = 14,
    [int]`$MaxEventsPerLog = 3000,
    [switch]`$SkipEvtxExport,
    [switch]`$SkipHashing,
    [switch]`$LoadUserHives,
    [switch]`$IncludeFileTimeline,
    [switch]`$IncludeUsnJournal,
    [switch]`$NoZip,
    [switch]`$RequireAdministrator
)

`$ErrorActionPreference = 'Continue'
`$ProgressPreference = 'SilentlyContinue'
`$script:FotonModuleRoot = `$PSScriptRoot
`$script:FotonSrcRoot = `$null
`$script:FotonSession = @{ Version = '$version' }
`$script:FotonEmbeddedPatterns = @{
    UserWritablePatterns      = $(ConvertTo-FotonQuotedArrayLiteral $writable)
    SuspiciousCommandPatterns = $(ConvertTo-FotonQuotedArrayLiteral $suspicious)
    RemoteAccessToolNames     = $(ConvertTo-FotonQuotedArrayLiteral $rats)
    HardeningCsv              = @'
$hardeningCsv
'@
}

"@

$footer = @"

# Generated entry: bind this file's parameters into the orchestrator.
Invoke-FotonTriage @PSBoundParameters
"@

$destDir = Split-Path $OutputPath -Parent
if (-not (Test-Path -LiteralPath $destDir)) {
    New-Item -Path $destDir -ItemType Directory -Force | Out-Null
}

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($OutputPath, ($header + $chunks.ToString() + $footer), $utf8)

$parseErrors = $null
$null = [System.Management.Automation.Language.Parser]::ParseFile($OutputPath, [ref]$null, [ref]$parseErrors)
if ($parseErrors -and $parseErrors.Count -gt 0) {
    $parseErrors | ForEach-Object { Write-Host "LINE $($_.Extent.StartLineNumber): $($_.Message)" -ForegroundColor Red }
    throw "Generated $OutputPath has parse errors."
}

if ($aliasPath) {
    Copy-Item -LiteralPath $OutputPath -Destination $aliasPath -Force
}

Write-Host "Wrote $OutputPath ($([math]::Round((Get-Item $OutputPath).Length / 1KB, 1)) KB, $($files.Count) source files, v$version, collect schema $collectSchema)" -ForegroundColor Green
if ($aliasPath) {
    Write-Host "Also wrote $aliasPath (same bytes; stable name for docs and RMM)." -ForegroundColor Green
    Write-Host 'Copy the versioned file to the endpoint so the schema is visible in the leaf name. Do not copy the module tree.' -ForegroundColor DarkGray
} else {
    Write-Host 'Copy this file to the endpoint. Do not copy the module tree.' -ForegroundColor DarkGray
}
